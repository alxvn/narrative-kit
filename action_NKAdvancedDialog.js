/**
 * @param { ccbNode } nodeToShow
 * @param { DialogLine[] } lines
 * @param { number } interactionKey
 * @param { ccbNode } node
 * @param { any } actionOnComplete
 * @param { boolean } doNotGiveBackControl
 * @param { boolean } typewriterEnabled
 * @param { number } charDelayMs
 * @param { ccbNode } typewriterSoundNode
 * @param { Object.<string, any> } lineActions - maps 'action_1'..'action_15' to editor action properties
 */
action_NKAdvancedDialog.prototype.buildDialogHandler = function (
    nodeToShow,
    lines,
    interactionKey,
    node,
    actionOnComplete,
    doNotGiveBackControl,
    typewriterEnabled,
    charDelayMs,
    typewriterSoundNode,
    lineActions
) {
    var hasTypewriterSound = typewriterSoundNode &&
        ccbGetSceneNodeProperty(typewriterSoundNode, 'Type') !== 'unknown';

    function playTypewriterSound() {
        if (hasTypewriterSound) {
            ccbSetSceneNodeProperty(typewriterSoundNode, 'PlayMode', 'nothing');
            ccbSetSceneNodeProperty(typewriterSoundNode, 'PlayMode', 'play_once');
        }
    }
    var lineIndex = 0;
    var curText = '';
    var phraseCompleted = false;
    var lastCharTime = 0;
    var waitingForDelay = false;
    var delayUntil = 0;

    function invokeLineAction(actionRef) {
        if (!actionRef) {
            return;
        }
        var action = typeof actionRef === 'string' ? lineActions[actionRef] : actionRef;
        if (action) {
            ccbInvokeAction(action, node);
        }
    }

    function getSpeakerPrefix(entry) {
        return entry.speaker ? entry.speaker + ':\r\n\r\n' : '';
    }

    function finishDialog() {
        okeEventHandler.unregisterEvent(inner);
        ccbSetSceneNodeProperty(nodeToShow, 'Visible', false);
        if (!doNotGiveBackControl && typeof interactablesManager !== 'undefined') {
            interactablesManager.scheduleTurnOn();
        }
        if (actionOnComplete) {
            ccbInvokeAction(actionOnComplete, node);
        }
    }

    function startLine(entry) {
        invokeLineAction(entry.preAction);
        var speakerPrefix = getSpeakerPrefix(entry);
        curText = speakerPrefix;
        phraseCompleted = !typewriterEnabled;
        lastCharTime = Date.now();
        if (phraseCompleted) {
            curText = speakerPrefix + entry.line;
        }
        ccbSetSceneNodeProperty(nodeToShow, 'Text', curText);
    }

    function advanceToNextLine() {
        var entry = lines[lineIndex];
        invokeLineAction(entry.postAction);

        var delayMs = entry.delay;
        if (delayMs != null && delayMs > 0) {
            ccbSetSceneNodeProperty(nodeToShow, 'Visible', false);
            waitingForDelay = true;
            delayUntil = Date.now() + delayMs;
            return;
        }

        lineIndex += 1;
        if (lineIndex >= lines.length) {
            finishDialog();
            return;
        }
        startLine(lines[lineIndex]);
    }

    startLine(lines[0]);

    function inner() {
        ccbSetMousePos(ccbGetScreenWidth() / 2, ccbGetScreenHeight() / 2);

        if (waitingForDelay) {
            if (Date.now() >= delayUntil) {
                waitingForDelay = false;
                lineIndex += 1;
                if (lineIndex >= lines.length) {
                    finishDialog();
                    return;
                }
                ccbSetSceneNodeProperty(nodeToShow, 'Visible', true);
                startLine(lines[lineIndex]);
            }
            return;
        }

        var entry = lines[lineIndex];
        var speakerPrefix = getSpeakerPrefix(entry);
        var fullText = speakerPrefix + entry.line;
        var now = Date.now();

        if (!phraseCompleted) {
            if (typeof isJustPressed === 'function' && isJustPressed(interactionKey)) {
                curText = fullText;
                phraseCompleted = true;
            } else if (lastCharTime + charDelayMs < now) {
                lastCharTime = now;
                var lineIndexInText = curText.length - speakerPrefix.length;
                var charToAdd = entry.line[lineIndexInText];
                if (charToAdd === undefined) {
                    phraseCompleted = true;
                } else {
                    curText += charToAdd;
                    phraseCompleted = curText.length === fullText.length;
                    if (hasTypewriterSound && NK_ADVANCED_DIALOG_VOWELS.indexOf(charToAdd) === -1) {
                        playTypewriterSound();
                    }
                }
            }
            ccbSetSceneNodeProperty(nodeToShow, 'Text', curText);
        } else if (typeof isJustPressed === 'function' && isJustPressed(interactionKey)) {
            if (lineIndex >= lines.length - 1) {
                invokeLineAction(entry.postAction);
                finishDialog();
                return;
            }
            advanceToNextLine();
        }
    }

    return inner;
}
