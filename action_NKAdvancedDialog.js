var okeDialogs;

var NK_ADVANCED_DIALOG_VOWELS = ['a', 'A', 'e', 'E', 'y', 'Y', 'u', 'U', 'i', 'I', 'o', 'O'];

/**
 * @typedef DialogLine
 * @property { string } line
 * @property { string | null } speaker
 * @property { string | null } [preAction] - e.g. 'action_1', invoked when the line starts
 * @property { string | null } [postAction] - e.g. 'action_2', invoked when advancing to the next line
 * @property { number | null } [delay] - ms to wait before the next line; nodeToShow is hidden during this time
 */

action_NKAdvancedDialog = function () {}

action_NKAdvancedDialog.prototype.execute = function (node) {
    if (!this.nodeToShow || ccbGetSceneNodeProperty(this.nodeToShow, 'Type') === 'unknown') {
        print('NK Advanced dialog: nodeToShow is not set or invalid.');
        return;
    }

    if (!okeDialogs) {
        print('NK Advanced dialog: dialogs are not initialized. Have you added the extension generated by the Dialog app?')
    }

    var lines = okeDialogs[this.dialogName];

    if (!lines) {
        print('NK Advanced dialog: not able to find dialog "' + this.dialogName + '"');
    }
    if (!lines.length) {
        print('NK Advanced dialog: no dialog lines to show.');
        return;
    }

    var interactionKey = parseInt(this.interactionKey, 10);
    var lineActions = {};
    for (var a = 1; a <= 15; a++) {
        lineActions['action_' + a] = this['action_' + a];
    }
    var dialogFunc = this.buildDialogHandler(
        this.nodeToShow,
        lines,
        interactionKey,
        node,
        this.actionOnComplete,
        this.doNotGiveBackControl,
        this.typewriterEnabled,
        this.charDelayMs,
        this.typewriterSoundNode,
        lineActions
    );

    ccbSetSceneNodeProperty(this.nodeToShow, 'Visible', true);
    okeEventHandler.registerEvent(dialogFunc);
}

